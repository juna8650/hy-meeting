/**
 * 주어진 날짜(YYYY-MM-DD)의 공휴일 명칭 반환 (공휴일이 아니면 null)
 */
export function getKoreanHolidayName(dateStr: string): string | null {
  if (!dateStr) return null;

  // 1. 가변 공휴일 확인 (설날, 추석, 대체공휴일, 선거일 등)
  if (VARIABLE_HOLIDAYS[dateStr]) {
    return VARIABLE_HOLIDAYS[dateStr];
  }

  // 2. 양력 고정 공휴일 확인
  const parts = dateStr.split('-');
  if (parts.length === 3) {
    const monthDay = `${parts[1]}-${parts[2]}`;
    if (SOLAR_FIXED_HOLIDAYS[monthDay]) {
      return SOLAR_FIXED_HOLIDAYS[monthDay];
    }
  }

  return null;
}

/**
 * 주어진 날짜(YYYY-MM-DD)가 공휴일(또는 일요일)인지 여부 확인
 */
export function isKoreanHoliday(dateStr: string): boolean {
  return getKoreanHolidayName(dateStr) !== null;
}

/**
 * 캘린더에서 빨간색으로 표시해야 하는 날인지 여부 (일요일 또는 법정공휴일)
 */
export function isRedDay(dateStr: string): boolean {
  if (!dateStr) return false;
  const [y, m, d] = dateStr.split('-').map(Number);
  const date = new Date(y, m - 1, d);
  const isSunday = date.getDay() === 0;
  return isSunday || isKoreanHoliday(dateStr);
}
